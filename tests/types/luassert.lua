---@alias luassert.Near fun(expected: number, actual: number, tolerance: number, message?: string)
---@alias luassert.Error fun(func: function, err?: any, message?: string)
---@alias luassert.ErrorMatch fun(func: function, pattern: string, init?: integer, plain?: boolean, message?: string)
---@alias luassert.Returned fun(count: integer, ...: any)

