---@meta

-- luassert, the `assert` plenary's busted runner gives specs. A key is a chain of modifier and assertion
-- tokens, so these list each assertion bare, behind one modifier, and behind a modifier and a negation. Every
-- assertion takes an optional failure message after its arguments.
-- Calling `assert(v, message)` works at runtime, but the class declares no call, so a bare `assert(v)` fails the type
-- check and specs call the named assertions.

---@alias luassert.Value fun(value: any, message?: string)
---@alias luassert.Pair fun(expected: any, actual: any, message?: string)
---@alias luassert.Unique fun(list: table, deep?: boolean, message?: string)
